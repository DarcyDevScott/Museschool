/* Concatenates the whole application into one Markdown file, so another
 * machine (or another Claude) can read the entire thing in one pass.
 *   node make-source-md.mjs
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { extname } from 'node:path';

const GROUPS = [
  ['The quiz and content', [
    'src/data/quiz.js', 'src/data/tasks.js', 'src/data/lessons.js', 'src/data/phases.js'
  ]],
  ['The engine', ['src/engine/engine.js']],
  ['Storage, backup and counting', ['src/store.js', 'src/backup.js', 'src/insight.js']],
  ['The interface (quiz, reveal, today, plan, learn, progress, journal, settings)', [
    'src/ui/quiz-ui.js', 'src/ui/app-ui.js', 'src/styles.css'
  ]],
  ['Shell, service worker, manifest', ['index.html', 'sw.js', 'manifest.webmanifest']],
  ['Landing page', ['landing/index.html']],
  ['Infrastructure', [
    'analytics/worker.js', 'mcp/server.mjs', 'build.mjs', 'rename.mjs', 'wrangler.jsonc'
  ]]
];

const LANG = { '.js': 'javascript', '.mjs': 'javascript', '.css': 'css',
               '.html': 'html', '.webmanifest': 'json', '.jsonc': 'jsonc' };

let out = `# Mendday — full source

Every file of the application, current as of ${new Date().toISOString().slice(0, 10)}.
Generated by \`node make-source-md.mjs\` — regenerate rather than editing this by hand.

Read \`HANDOFF.md\` first for what any of it is for.

## Contents

`;

for (const [title, files] of GROUPS) {
  out += `- **${title}** — ${files.map((f) => `\`${f}\``).join(', ')}\n`;
}
out += '\n---\n';

for (const [title, files] of GROUPS) {
  out += `\n# ${title}\n`;
  for (const f of files) {
    const body = readFileSync(f, 'utf8');
    const kb = (statSync(f).size / 1024).toFixed(1);
    out += `\n## \`${f}\`\n\n_${kb} KB, ${body.split('\n').length} lines_\n\n`;
    out += '```' + (LANG[extname(f)] || '') + '\n' + body.replace(/\n$/, '') + '\n```\n';
  }
}

writeFileSync('SOURCE.md', out);
console.log(`wrote SOURCE.md — ${(out.length / 1024).toFixed(0)} KB, ` +
            `${GROUPS.reduce((n, g) => n + g[1].length, 0)} files`);
